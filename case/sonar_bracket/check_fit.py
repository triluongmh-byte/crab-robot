"""Fit, motion and beam checks for the sonar bracket against the generated A1V4-r5 robot exports.

Reads the exported STEP files of the robot (case/robot/*.step, generated by ./build.sh, outside Git) and the
bracket source next to this file. Writes fit_report.json and sonar_bracket_fit_preview.step here.

Usage:  python3 case/sonar_bracket/check_fit.py [--robot-dir DIR] [--coarse]
        DIR defaults to ../robot (this worktree), falling back to the main harness checkout if absent.
"""
import argparse
import concurrent.futures as cf
import itertools
import json
import math
import sys
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import cadquery as cq  # noqa: E402
import sonar_bracket as SB  # noqa: E402

# Robot exports (case/robot) are generated by ./build.sh and kept out of Git;
# set CRAB_CASE_EXPORTS to another checkout's case/ if this one has none.
FALLBACK = Path(os.environ.get('CRAB_CASE_EXPORTS', str(HERE.parent)))
CORNERS = ('FL', 'FR', 'RL', 'RR')
FRONT = ('RL', 'RR')                       # the -X end legs = CH4..CH7 = walking front
HIP = {'FL': (53.25, 22.8), 'FR': (53.25, -22.8), 'RL': (-53.25, 22.8), 'RR': (-53.25, -22.8)}
SIGN = {'FL': (1, 1), 'FR': (1, -1), 'RL': (-1, 1), 'RR': (-1, -1)}
R_KNEE, Z_KNEE = 30.0, 52.6               # model.py
GROUND_Z = -16.5                          # model.py GROUND_Z (foot tip radius 4.5 below FOOT_TIP z -12)
BEAM_HALF_DEG = 15.0                      # HC-SR04 "measuring angle 15 deg", taken as the half-angle (conservative)
BEAM_LEN = 600.0
TOL = 0.05                                # mm3 overlap treated as numeric noise
ROBOT = None
_cache = {}


def robot_dir(arg):
    for d in ([Path(arg)] if arg else []) + [HERE.parent / 'robot', FALLBACK / 'robot']:
        if (d / 'frame_lower.step').exists():
            return d
    raise SystemExit('No robot exports found: run ./build.sh or pass --robot-dir')


def load(name):
    if name not in _cache:
        _cache[name] = cq.importers.importStep(str(ROBOT / f'{name}.step'))
    return _cache[name]


def servo_solids():
    """ref_DO_NOT_PRINT_servos order (case/build.py): per corner [hip, hip horn, knee (+horn)]."""
    sv = load('ref_DO_NOT_PRINT_servos').solids().vals()
    out = {}
    for i, c in enumerate(CORNERS):
        out[f'SG90 hip {c}'], out[f'hip horn {c}'], out[f'SG90 knee {c}'] = sv[3 * i:3 * i + 3]
    return out


def min_distance(a, b):
    from OCP.BRepExtrema import BRepExtrema_DistShapeShape
    d = BRepExtrema_DistShapeShape(a.wrapped, b.wrapped)
    d.Perform()
    return d.Value() if d.IsDone() else -1.0


def overlap(a, b):
    ba, bb = a.BoundingBox(), b.BoundingBox()
    if ba.xmax < bb.xmin or bb.xmax < ba.xmin or ba.ymax < bb.ymin or bb.ymax < ba.ymin or ba.zmax < bb.zmin or bb.zmax < ba.zmin:
        return 0.0
    try:
        return a.intersect(b).Volume()
    except Exception:
        return -1.0


def leg_pose(c, hip, knee):
    """Same convention as tools/case/mech_check.py leg_pose: mirrored legs move as mirror images.
    Returns (thigh, foot, knee servo) at the pose."""
    sx, sy = SIGN[c]
    hx, hy = HIP[c]
    th = load(f'thigh_{c}').val()
    ft = load(f'foot_{c}').val()
    ks = servo_solids()[f'SG90 knee {c}']
    a = math.radians(45)
    kx, ky = hx + sx * R_KNEE * math.cos(a), hy + sy * R_KNEE * math.sin(a)
    td = (sx * -math.sin(a), sy * math.cos(a), 0)
    if knee:
        ft = ft.rotate(cq.Vector(kx, ky, Z_KNEE), cq.Vector(kx + td[0], ky + td[1], Z_KNEE), sx * sy * knee)
    if hip:
        g = sx * sy * hip
        ax0, ax1 = cq.Vector(hx, hy, 0), cq.Vector(hx, hy, 1)
        th, ft, ks = th.rotate(ax0, ax1, g), ft.rotate(ax0, ax1, g), ks.rotate(ax0, ax1, g)
    return [('thigh', th), ('foot', ft), ('knee servo', ks)]


# ------------------------------------------------------------------------------------------- our parts in the robot frame
def tie_bands():
    """Two 2.5 x 1.2 zip ties looped around the deck end bar through the base slots (robot frame)."""
    p = SB.P
    x_face, xb = p.face_x_cad, p.face_x_cad + p.bar_t          # -63, -60
    x_front = p.face_x_cad - p.base_depth                          # base front face (-72)
    out = []
    for sy in (1, -1):
        y0, y1 = sorted((sy * (p.tie_y - 1.25), sy * (p.tie_y + 1.25)))
        z0, z1 = p.dbar_z[0] - 1.2, p.dbar_z[1] + 1.2
        ring = SB.box(x_front - 1.2, xb + 1.2, y0, y1, z0, z1).cut(SB.box(x_front, xb, y0 - 1, y1 + 1, p.dbar_z[0], p.dbar_z[1]))
        out.append((f'zip tie y{sy * p.tie_y:+.1f} (part inside base slots and around the bar)', ring))
    return out


def usb_cable():
    """Port-1 USB cable (D29 route) re-laid to cross the end window at z 30.6, through the bracket channel. Tube Ø4.5 (GIA DINH)."""
    pts = [(-53.0, 3.0, 19.0), (-53.0, 0.0, 28.0), (-60.5, 0.0, 28.0), (-63.5, 0.0, 30.6), (-65.6, 0.0, 30.6), (-65.6, 40.6, 30.6), (-50.0, 40.6, 30.6)]
    segs = []
    for a, b in zip(pts, pts[1:]):
        va, vb = cq.Vector(*a), cq.Vector(*b)
        d = vb - va
        segs.append(cq.Solid.makeCylinder(2.25, d.Length, va, d.normalized()))
        segs.append(cq.Solid.makeSphere(2.25, angleDegrees1=-90, angleDegrees2=90).translate(vb))
    s = segs[0]
    for t in segs[1:]:
        s = s.fuse(t)
    return s


def cone(apex, axis, half_deg=BEAM_HALF_DEG, length=BEAM_LEN, r0=8.0):
    """Beam: truncated cone starting at the can face (radius r0) and opening at half_deg."""
    v = cq.Vector(*axis).normalized()
    r1 = r0 + length * math.tan(math.radians(half_deg))
    return cq.Solid.makeCone(r0, r1, length, cq.Vector(*apex), v)


def floor_hit(apex, axis):
    """Horizontal range where the lower beam edge reaches the floor (GROUND_Z), from the can centre."""
    pitch = math.degrees(math.asin(axis[2]))
    lower = BEAM_HALF_DEG - pitch
    h = apex[2] - GROUND_Z
    return None if lower <= 0 else h / math.tan(math.radians(lower))


# ------------------------------------------------------------------------------------------- jobs (process pool)
def _init(rd):
    global ROBOT
    ROBOT = Path(rd)


def ours():
    return [('bracket', SB.robot_frame())] + SB.module_dummies_robot(header='inplane') + \
        [(n.replace('HC-SR04P', 'HC-SR04P(back-pin)'), s) for n, s in SB.module_dummies_robot(header='back') if 'plug' in n or 'header' in n] + tie_bands()


def sweep_job(args):
    c, hip, knee = args
    mine = ours()
    best = (1e9, '')
    hits = []
    for ml, m in leg_pose(c, hip, knee):
        for ol, o in mine:
            d = min_distance(m, o)
            if d < best[0]:
                best = (d, f'{c} {ml} vs {ol}')
            if d < 1e-3:
                v = overlap(m, o)
                if v > TOL:
                    hits.append({'leg': f'{c} {ml}', 'with': ol, 'overlapMm3': round(v, 2)})
    return {'corner': c, 'hip': hip, 'knee': knee, 'minClearanceMm': round(best[0], 2), 'closest': best[1], 'collisions': hits}


def leg_leg_job(args):
    hip, knee = args
    a = leg_pose('RL', hip, knee)
    b = leg_pose('RR', hip, knee)
    return hip, knee, round(min(min_distance(x, y) for _, x in a for _, y in b), 2)


def beam_leg_job(args):
    c, hip, knee = args
    out = []
    for lab, apex, axis in SB.beams_robot():
        cn = cone(apex, axis)
        for ml, m in leg_pose(c, hip, knee):
            v = overlap(cn, m)
            if v > TOL:
                i = cn.intersect(m)
                d = min_distance(cq.Vertex.makeVertex(*apex), i)
                out.append({'beam': lab, 'leg': f'{c} {ml}', 'hip': hip, 'knee': knee, 'rangeMm': round(d, 1), 'volMm3': round(v, 1)})
    return out


def main():
    global ROBOT
    ap = argparse.ArgumentParser()
    ap.add_argument('--robot-dir')
    ap.add_argument('--coarse', action='store_true')
    a = ap.parse_args()
    ROBOT = robot_dir(a.robot_dir)
    rep = {'robotExports': str(ROBOT), 'convention': 'robot (CAD) frame of case/model.py: +X = bank end, -X = walking front (CH4/CH6)',
           'beamHalfAngleDeg': BEAM_HALF_DEG}

    # 1. static: bracket + modules + ties + cable vs body, servos, screws, electronics at neutral
    body = [('frame_lower', load('frame_lower').val()), ('frame_upper', load('frame_upper').val())]
    sv = servo_solids()
    body += [(k, v) for k, v in sv.items()]
    body += [(f'hardware #{i}', s) for i, s in enumerate(load('ref_DO_NOT_PRINT_hardware').solids().vals())]
    body += [(f'electronics #{i}', s) for i, s in enumerate(load('ref_DO_NOT_PRINT_electronics').solids().vals())]
    mine = ours()
    static = []
    for ml, m in mine:
        for bl, b in body:
            bb, mb = b.BoundingBox(), m.BoundingBox()
            if bb.xmin > mb.xmax + 5 or mb.xmin > bb.xmax + 5 or bb.zmin > mb.zmax + 5 or mb.zmin > bb.zmax + 5 or bb.ymin > mb.ymax + 5 or mb.ymin > bb.ymax + 5:
                continue
            d = min_distance(m, b)
            v = overlap(m, b) if d < 1e-3 else 0.0
            static.append({'ours': ml, 'body': bl, 'minDistanceMm': round(d, 2), 'overlapMm3': round(v, 2)})
    static.sort(key=lambda r: r['minDistanceMm'])
    intended = lambda r: r['ours'] == 'bracket' and r['body'] in ('frame_lower', 'frame_upper') or r['ours'].startswith('zip tie') and r['body'] == 'frame_lower'
    rep['static'] = {'closest': static[:12], 'collisions': [r for r in static if r['overlapMm3'] > TOL],
                     'note': 'bracket touching frame_lower (deck end bar face) and frame_upper (end bar face + top) and the ties wrapping the deck bar are the intended contacts'}
    rep['static']['unintendedCollisions'] = [r for r in rep['static']['collisions'] if not intended(r)]
    # module vs bracket (the modules must sit in the holder without overlap)
    br = mine[0][1]
    rep['moduleInHolder'] = [{'module part': ml, 'overlapWithBracketMm3': round(overlap(m, br), 3), 'minDistanceMm': round(min_distance(m, br), 2)}
                             for ml, m in mine[1:] if 'zip tie' not in ml]
    cab = usb_cable()
    rep['usbCable'] = {'route': 'D29 port-1 cable, under the centre saddle at z 28, then rising to z 30.6 at the end window to lie in the bracket channel (D29 used z 26)',
                       'minDistanceToBracketMm': round(min_distance(cab, br), 2),
                       'minDistanceToTiesMm': round(min(min_distance(cab, t) for _, t in tie_bands()), 2),
                       'minDistanceToFrameMm': round(min(min_distance(cab, load(n).val()) for n in ('frame_lower', 'frame_upper')), 2)}

    # 2. leg sweeps
    hips = range(-30, 31, 15) if a.coarse else range(-30, 31, 10)
    knees = (-35, 0, 35) if a.coarse else (-35, -30, -15, 0, 15, 30, 35)
    grid = [(c, h, k) for c in FRONT for h in hips for k in knees]
    flick = [(c, s * h, k) for c in FRONT for s in (1, -1) for h in range(40, 91, 10 if a.coarse else 5) for k in (-30, 0, 30)]
    with cf.ProcessPoolExecutor(initializer=_init, initargs=(str(ROBOT),)) as ex:
        trot = list(ex.map(sweep_job, grid))
        fl = list(ex.map(sweep_job, flick))
        ll = list(ex.map(leg_leg_job, [(s * h, k) for s in (1, -1) for h in range(30, 91, 5) for k in (-30, 0, 30)]))
        bl = list(ex.map(beam_leg_job, [(c, h, k) for c in FRONT for h in range(-30, 31, 15) for k in (-35, 0, 35)]))
    worst = min(trot, key=lambda r: r['minClearanceMm'])
    rep['trotGrid'] = {'poses': len(trot), 'hipDeg': [min(hips), max(hips)], 'kneeDeg': [min(knees), max(knees)],
                       'minClearanceMm': worst['minClearanceMm'], 'worst': worst, 'collisions': [r for r in trot if r['collisions']]}

    def first_contact(rows, sgn):
        bad = sorted({abs(r['hip']) for r in rows if (r['hip'] > 0) == (sgn > 0) and r['collisions']})
        return bad[0] if bad else None
    rep['flick'] = {'hipDegTested': '±40..90', 'firstBracketContactHipDeg': {'+': first_contact(fl, 1), '-': first_contact(fl, -1)},
                    'contacts': [r for r in fl if r['collisions']][:10]}
    lfirst = {}
    for sgn in (1, -1):
        bad = sorted(abs(h) for h, k, d in ll if (h > 0) == (sgn > 0) and d < 0.01)
        lfirst['+' if sgn > 0 else '-'] = bad[0] if bad else None
    rep['flick']['frontLegsTouchEachOtherFromHipDeg'] = lfirst
    # which sign swings the front feet forward (toward -X)?
    fx = {}
    for sgn in (1, -1):
        ft = dict(leg_pose('RL', sgn * 60, 0))['foot'].Center()
        fx['+' if sgn > 0 else '-'] = round(ft.x, 1)
    rep['flick']['footCentreXAtHip60'] = fx

    # 3. beams
    beams = []
    for lab, apex, axis in SB.beams_robot():
        cn = cone(apex, axis)
        hits = []
        for ol, o in [('bracket', br)] + [(n, s) for n, s in mine[1:] if 'zip tie' not in n] + body:
            if overlap(cn, o) > TOL:
                hits.append({'with': ol, 'rangeMm': round(min_distance(cq.Vertex.makeVertex(*apex), cn.intersect(o)), 1)})
        beams.append({'beam': lab, 'faceCentre': [round(v, 1) for v in apex], 'axis': [round(v, 3) for v in axis],
                      'yawDegTowardRobotLeft': round(math.degrees(math.atan2(-axis[1], -axis[0])), 1), 'pitchDeg': round(math.degrees(math.asin(axis[2])), 1),
                      'heightAboveFloorMm': round(apex[2] - GROUND_Z, 1), 'floorHitRangeMm': round(floor_hit(apex, axis), 0),
                      'staticObstaclesInCone': hits})
    rep['beams'] = beams
    legb = [h for rows in bl for h in rows]
    rep['beamVsFrontLegs'] = {'gridHipDeg': '-30..30 step 15', 'gridKneeDeg': [-35, 0, 35],
                              'entries': sorted(legb, key=lambda r: r['rangeMm'])[:10], 'count': len(legb)}
    bb = SB.robot_frame().BoundingBox()
    rep['bracketRobotBBox'] = [[round(bb.xmin, 1), round(bb.ymin, 1), round(bb.zmin, 1)], [round(bb.xmax, 1), round(bb.ymax, 1), round(bb.zmax, 1)]]
    (HERE / 'fit_report.json').write_text(json.dumps(rep, indent=1, ensure_ascii=False))

    # 4. preview assembly (robot frame)
    asm = cq.Assembly(name='sonar_bracket_fit_preview')
    asm.add(SB.robot_frame(), name='sonar_bracket', color=cq.Color(0.95, 0.55, 0.1))
    for n, s in SB.module_dummies_robot():
        asm.add(s, name=n.replace(' ', '_'), color=cq.Color(0.1, 0.35, 0.8) if 'pcb' in n else cq.Color(0.75, 0.75, 0.78))
    for n, s in tie_bands():
        asm.add(s, name=f'zip_tie_{n[9:13].strip()}', color=cq.Color(0.1, 0.1, 0.1))
    asm.add(cab, name='usb_cable_port1', color=cq.Color(0.2, 0.3, 0.9))
    for n in ('frame_lower', 'frame_upper'):
        asm.add(load(n).val(), name=n, color=cq.Color(0.85, 0.85, 0.85))
    for c in FRONT:
        asm.add(sv[f'SG90 hip {c}'], name=f'SG90_hip_{c}', color=cq.Color(0.2, 0.4, 0.9))
        for ml, m in leg_pose(c, 0, 0):
            asm.add(m, name=f'{ml.replace(" ", "_")}_{c}', color=cq.Color(0.9, 0.4, 0.2) if ml != 'knee servo' else cq.Color(0.2, 0.4, 0.9))
    asm.save(str(HERE / 'sonar_bracket_fit_preview.step'))
    print(json.dumps({k: rep[k] for k in ('static', 'usbCable', 'trotGrid', 'flick')}, indent=1)[:6000])


if __name__ == '__main__':
    main()
