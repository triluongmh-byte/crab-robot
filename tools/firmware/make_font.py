#!/usr/bin/env python3
"""Generate a compact Vietnamese LCD bitmap font; runtime needs no filesystem."""
from pathlib import Path
import sys,os
ROOT=Path(__file__).resolve().parents[2]
cache=Path(os.environ.get('CIRCUIT_FIRMWARE_CACHE',str(Path.home()/'.cache/autonomous-circuit/firmware')))
sys.path.insert(0,str(cache/'python-deps'))
from PIL import Image,ImageFont,ImageDraw
font_path=Path('/System/Library/Fonts/Supplemental/Arial.ttf')
font=ImageFont.truetype(str(font_path),13)
# Printable ASCII plus all Vietnamese Latin precomposed letters; 10x18 cell.
chars=sorted(set(range(32,127))|set(range(0x1EA0,0x1EFA))|set(map(ord,'ÀÁÂÃÈÉÊÌÍÒÓÔÕÙÚÝàáâãèéêìíòóôõùúýĂăĐđĨĩŨũƠơƯư')))
rows=[]
for cp in chars:
 im=Image.new('1',(10,18));d=ImageDraw.Draw(im);d.text((0,0),chr(cp),font=font,fill=1)
 b=[]
 for y in range(18):
  for x0 in (0,8):
   b.append(sum((int(im.getpixel((x,y))) if x<10 else 0)<<(7-(x-x0)) for x in range(x0,x0+8)))
 rows.append('{'+str(cp)+', {'+','.join(map(str,b))+'}}')
out='#pragma once\n// Generated by tools/firmware/make_font.py; Arial bitmap cells, 10x18.\nstruct Glyph { unsigned short cp; unsigned char bits[36]; };\nstatic const Glyph glyphs[]={\n'+',\n'.join(rows)+'\n};\n'
path=ROOT/'firmware/crab/Font.h'
if not path.exists() or path.read_text()!=out:path.write_text(out)
print(len(rows),'glyphs')
